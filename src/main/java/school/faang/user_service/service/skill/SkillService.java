package school.faang.user_service.service.skill;

import school.faang.user_service.dto.skill.CreateSkillDto;
import school.faang.user_service.dto.skill.SkillCandidateDto;
import school.faang.user_service.dto.skill.SkillDto;

import java.util.List;

/**
 * Сервис для управления скиллами (навыками) пользователей.
 *
 * Предоставляет функционал:
 * <ul>
 *     <li>Создание новых скиллов в системе</li>
 *     <li>Получение списка скиллов, присвоенных пользователю</li>
 *     <li>Получение списка скиллов, которые были предложены пользователю другими пользователями</li>
 *     <li>Приобретение пользователем предложенных скиллов при соблюдении бизнес-ограничений</li>
 * </ul>
 *
 * Бизнес-правила:
 * <ul>
 *     <li>Скилл должен быть уникальным по названию</li>
 *     <li>Пользователь может просматривать только свои предложенные скиллы</li>
 *     <li>Скилл может быть присвоен пользователю, только если его предложили минимум три разных пользователя</li>
 *     <li>Пользователь не может повторно присвоить себе уже имеющийся у него скилл</li>
 *     <li>Приобрести скилл может только тот пользователь, которому он был предложен</li>
 * </ul>
 */
public interface SkillService {

    /**
     * Создаёт новый скилл в системе.
     * <p>
     * Условия:
     * <ul>
     *     <li>Название скилла должно быть уникальным —
     *         в противном случае выбрасывается {@code DataValidationException}.</li>
     * </ul>
     *
     * @param skillDto объект {@link CreateSkillDto}, содержащий данные для создания нового скилла
     * @return объект {@link SkillDto}, представляющий созданный скилл
     */
    SkillDto create(CreateSkillDto skillDto);

    /**
     * Возвращает список скиллов, которыми владеет пользователь.
     *
     * @param userId идентификатор пользователя
     * @return список объектов {@link SkillDto}, представляющих скиллы пользователя
     */
    List<SkillDto> getByUserId(Long userId);

    /**
     * Возвращает список скиллов, которые были предложены пользователю другими пользователями.
     * <p>
     * Каждый элемент включает в себя сам скилл и количество предложений
     * (число пользователей, которые порекомендовали данный скилл).
     *
     * @param userId идентификатор пользователя, которому были предложены скиллы
     * @return список объектов {@link SkillCandidateDto}, содержащих информацию о предложенных скиллах
     */
    List<SkillCandidateDto> getOfferedSkills(long userId);

    /**
     * Позволяет пользователю присвоить себе предложенный скилл.
     * <p>
     * Условия:
     * <ul>
     *     <li>Скилл должен быть предложен минимум тремя разными пользователями.</li>
     *     <li>Пользователь не должен уже владеть этим скиллом.</li>
     *     <li>Приобрести скилл может только тот пользователь, которому он был предложен.</li>
     * </ul>
     * В процессе присвоения скиллу назначаются гаранты (users), которые его порекомендовали.
     * Если условия не выполнены, выбрасывается {@code ForbiddenException} или {@code DataValidationException}.
     *
     * @param skillId идентификатор скилла, который пользователь хочет присвоить
     * @param userId идентификатор пользователя, который пытается присвоить скилл
     */
    void acquireSkillFromOffers(long skillId, long userId);
}
